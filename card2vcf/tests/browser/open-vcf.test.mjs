import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import test from 'node:test';
import {chromium,expect} from '@playwright/test';
import {createApp} from '../../server.mjs';
import {readVcf} from '../../public/open-vcf.mjs';
import {vcard} from '../../public/vcard.mjs';
import {fixture} from '../fixtures/integration-contract.mjs';

const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4////fwAJ+wP9KobjigAAAABJRU5ErkJggg==','base64');
const listen=server=>new Promise(resolve=>server.listen(0,'127.0.0.1',()=>resolve('http://127.0.0.1:'+server.address().port)));

test('Open VCF appends a reviewable batch, supports Undo and Redo, and re-exports edits',{timeout:30000},async t=>{
 const app=createApp(),url=await listen(app);
 t.after(()=>{app.closeAllConnections();app.close();});
 const browser=await chromium.launch({channel:'msedge',headless:true});
 t.after(()=>browser.close());
 const page=await browser.newPage({acceptDownloads:true,viewport:{width:390,height:900}});
 const requests=[],errors=[];
 page.on('request',request=>requests.push(request));
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(url);
 await expect(page.locator('#status')).toContainText('Ready');
 await page.locator('#files').setInputFiles({name:'existing.png',mimeType:'image/png',buffer:png});
 const original=fixture(),photo='data:image/png;base64,'+png.toString('base64');
 original.firstMet={date:'2024-02-29',occasion:'Conference',location:'Main hall',notes:'Introduced by a colleague'};
 const compatible=fixture();compatible.display='Fictional Compatible';
 const buffer=Buffer.from(vcard(original,'structured',[photo])+vcard(compatible,'monica'));
 const chooser=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'Open VCF',exact:true}).click();
 await (await chooser).setFiles({name:'example.vcf',mimeType:'text/vcard',buffer});
 const people=page.locator('#people .person');
 await expect(page.locator('#status')).toContainText('Opened 2 contact(s) for review.');
 await expect(people).toHaveCount(3);
 await expect(page.locator('#selectionCount')).toHaveText('2 people selected');
 await expect(people.first().getByRole('checkbox')).not.toBeChecked();
 await expect(people.nth(1)).toHaveClass(/active/);
 await expect(page.locator('#images img')).toBeVisible();
 await page.locator('#undo').click();
 await expect(people).toHaveCount(1);
 await page.locator('#redo').click();
 await expect(people).toHaveCount(3);
 await people.nth(1).getByRole('button').click();
 await expect(page.locator('#images img')).toBeVisible();
 await expect(page.locator('.row-jobs')).toHaveCount(3);
 for(const [key,text] of Object.entries(original.firstMet)){
  await expect(page.locator('.first-met').getByLabel(key,{exact:true})).toHaveValue(text);
 }
 await expect(page.locator('#editor .row-whatsapp').first().getByLabel('Number source')).not.toHaveValue('');
 const phone=page.locator('.row-phones').first().getByLabel('value',{exact:true});
 await phone.fill('555-0111');
 await phone.press('Tab');
 await expect(page.locator('#editor .row-whatsapp').first().getByLabel('value',{exact:true})).toHaveValue('555-0111');
 await page.locator('#editor').getByRole('checkbox',{name:'Reviewed',exact:true}).first().check();
 await people.nth(1).getByRole('checkbox').check();
 await page.locator('#export').click();
 const download=page.waitForEvent('download');
 await page.locator('#combined').click();
 const [{person,photos}]=readVcf(await readFile(await (await download).path(),'utf8'));
 assert.equal(person.phones[0].value,'555-0111');
 assert.deepEqual(person.firstMet,original.firstMet);
 assert.equal(person.socials[1].phoneId,person.phones[0].id);
 assert.deepEqual(Buffer.from(await photos[0].arrayBuffer()),png);
 await page.locator('#exportDialog [data-close]').click();
 await people.nth(2).getByRole('button').click();
 await expect(page.locator('#images')).toContainText('No source images for this contact.');
 await expect(page.locator('.row-jobs')).toHaveCount(1);
 await expect(page.getByLabel('Notes',{exact:true}).first()).toHaveValue(/Other job: Former Example/);
 await page.locator('#uiLanguage').selectOption('zh-CN');
 await expect(page.locator('#openVcf')).toHaveText('打开 VCF');
 await page.locator('#vcfFile').setInputFiles({name:'broken.vcf',mimeType:'text/vcard',buffer:Buffer.from('BEGIN:VCARD')});
 await expect(page.locator('#status')).toHaveText('请选择有效的 vCard (.vcf) 文件。');
 await expect(people).toHaveCount(3);
 assert.ok(requests.every(request=>request.method()==='GET'&&(request.url().startsWith(url)||request.url().startsWith('blob:'))));
 assert.deepEqual(errors,[]);
});
